#!/usr/bin/env python3
"""Runs host/test_kernel.c against the real asteroids gadget code of one stage: the ua_* functions and the ud_* helpers
they call are cut out of that stage's sweet_usb.c, with every #define and the ud/ua state, and compiled against a mock
DWC3 (MMIO, commands, events, DMA memory), so the same tests run on the audited code and on the fixed code.

  python3 -I host/kernel-harness.py b2        the fixed patches (expect every test to pass)
  python3 -I host/kernel-harness.py b         the audited patches (the fix tests are expected to fail there)

Also checks the boot order in that stage's sweet_ufs.c (finding 1). Writes only under /tmp. Exit 0 when every test
passed."""
import os, pathlib, re, subprocess, sys, tempfile

here = pathlib.Path(__file__).resolve().parent
gadget = here.parent
root = gadget.parent.parent.parent
stage = sys.argv[1] if len(sys.argv) > 1 else 'b2'
src_dir = gadget / 'work' / stage / 'bsd/dev'
src = (src_dir / 'sweet_usb.c').read_text()
ufs = src_dir / 'sweet_ufs.c'
if not ufs.exists():            # the audited stage did not change it: the combined tree's file is what it ran with
    ufs = root / 'ios-asteroids/research/xnu-combined/dxb/xnu/bsd/dev/sweet_ufs.c'

SKIP = {'ua_rd', 'ua_wr', 'ua_if_inet6', 'ua_clocks_on', 'ua_smmu', 'ua_repeater_owner'}
UD = {'ud_epcmd', 'ud_start_trb', 'ud_start', 'ud_start_setup', 'ud_stall', 'ud_notify_connected', 'ud_notify_speed',
      'ud_bus_reset', 'ud_rx_arm', 'ud_sync'}

defines = [l for l in src.splitlines() if l.startswith('#define ')]
enums = re.findall(r'^enum \{[^\n]*\};$', src, re.M)
structs = re.findall(r'^static struct \{\n.*?^\} (?:ud|ua)(?: = [^\n]*)?;\n', src, re.S | re.M)
funcs = []
for m in re.finditer(r'^static ((?:inline )?[^\n;(]*?)\n(\w+)\(([^)\n]*)\)\n\{\n.*?^\}\n', src, re.S | re.M):
    ret, name, args = m.group(1), m.group(2), m.group(3)
    if name in SKIP or not (name.startswith('ua_') or name in UD):
        continue
    funcs.append((ret.replace('inline ', ''), name, args, m.group(0)))
gen = ['/* generated by kernel-harness.py from %s */' % src_dir, *defines, '', *enums, *structs, '']
gen += ['static %s %s(%s);' % (r, n, a) for r, n, a, _ in funcs]
gen += [b.replace('static inline', 'static', 1) for *_, b in funcs]
tmp = pathlib.Path(tempfile.mkdtemp(prefix='ugk-'))
(tmp / 'gen.c').write_text('\n'.join(gen) + '\n')

# Finding 1: in the asteroids branch, the USB start comes after sweet_reboot_asteroids_init().
u = ufs.read_text()
branch = u[u.index('never on another SoC.'):]
branch = branch[:branch.index('\n\t\treturn 0;')]
order_ok = 0 <= branch.index('sweet_reboot_asteroids_init();') < branch.index('sweet_usb_probe();')
print('%-4s %-58s %s' % ('ok' if order_ok else 'FAIL', 'F1 boot order: USB after the recovery init', ufs.name))

exe = tmp / 'test_kernel'
cc = ['cc', '-std=gnu11', '-w', '-I', str(src_dir), '-I', str(tmp), '-DGEN="gen.c"', str(here / 'test_kernel.c'), '-o', str(exe)]
p = subprocess.run(cc, capture_output=True, text=True)
if p.returncode:
    print(p.stdout + p.stderr)
    sys.exit('compile failed for stage ' + stage)
r = subprocess.run([str(exe)], capture_output=True, text=True, env=dict(os.environ, TMPDIR=str(tmp)))
print(r.stdout, end='')
if r.returncode not in (0, 1):
    print(r.stderr[-2000:])
sys.exit(0 if order_ok and r.returncode == 0 else 1)
